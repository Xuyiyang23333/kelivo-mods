/// 静态 Mod 注册表生成。
///
/// 只依赖 Dart SDK。输入是 CLI 从 `mod.json` 解析出的 [ModRegistration]，
/// 输出是 `lib/modding/mod_registry.g.dart` 的确定性内容。
library;

/// 注册表在合成树中的固定相对路径。
const String modRegistryPath = 'lib/modding/mod_registry.g.dart';

/// 生成注册表所需的最小 Mod 数据，不依赖 Loader 的配置模型。
class ModRegistration {
  const ModRegistration({
    required this.id,
    required this.importUri,
    required this.className,
    this.toolNames = const <String>[],
  });

  /// Mod 唯一标识，用于错误信息和生成代码的 import 前缀。
  final String id;

  /// 注册类的 import URI。
  ///
  /// `package:` URI 原样保留；相对路径按 `lib/` 解析（可显式写 `lib/` 前缀），
  /// 生成时转换为相对 `lib/modding/mod_registry.g.dart` 的 URI。
  final String importUri;

  /// 注册类的类名，生成时以无参构造函数实例化。
  final String className;

  /// Mod 声明拥有的工具名，用于跨 Mod 冲突检查。
  final List<String> toolNames;
}

/// 注册表输入不合法。
class ModRegistryException implements Exception {
  const ModRegistryException(this.message);

  final String message;

  @override
  String toString() => message;
}

/// 校验 Mod 顺序、id、import、类名和工具名声明。
void validateModRegistrations(List<ModRegistration> mods) {
  final ids = <String>{};
  final toolOwners = <String, String>{};
  for (final mod in mods) {
    _validateId(mod);
    if (!ids.add(mod.id)) {
      throw ModRegistryException('重复的 Mod id：${mod.id}');
    }
    _resolveImportUri(mod.id, mod.importUri);
    _validateClassName(mod.id, mod.className);
    final names = <String>{};
    for (final name in mod.toolNames) {
      if (name.isEmpty || name.trim() != name || name.contains(RegExp(r'\s'))) {
        throw ModRegistryException(
          'Mod ${mod.id} 的工具名不能为空、包含空白或首尾空格：'
          '${_quote(name)}',
        );
      }
      if (!names.add(name)) {
        throw ModRegistryException('Mod ${mod.id} 重复声明工具名：$name');
      }
      final owner = toolOwners[name];
      if (owner != null) {
        throw ModRegistryException('工具名 $name 同时由 Mod $owner 和 ${mod.id} 声明');
      }
      toolOwners[name] = mod.id;
    }
  }
}

/// 生成 `lib/modding/mod_registry.g.dart` 的完整内容。
///
/// Mod 顺序保持输入顺序；import 行按字母排序，便于稳定 diff。
String renderModRegistry(List<ModRegistration> mods) {
  validateModRegistrations(mods);

  final imports = <String>[];
  final entries = <String>[];
  final prefixes = <String>{};
  for (final mod in mods) {
    final prefix = _importPrefix(mod.id, prefixes);
    final uri = _resolveImportUri(mod.id, mod.importUri);
    imports.add("import '$uri' as $prefix;");
    entries.add('  $prefix.${mod.className}(),');
  }
  imports.sort();

  final buffer = StringBuffer()
    ..writeln('// GENERATED CODE - DO NOT MODIFY BY HAND.')
    ..writeln('// Generated by kelivo_mod_loader (tool/src/registry.dart).')
    ..writeln(
      '// ignore_for_file: prefer_const_constructors, '
      'prefer_const_declarations, '
      'prefer_const_literals_to_create_immutables',
    )
    ..writeln('// dart format off')
    ..writeln()
    ..writeln("import 'tool_mod.dart';");
  for (final line in imports) {
    buffer.writeln(line);
  }
  buffer
    ..writeln()
    ..writeln('/// Mods in the load order declared by mods.json.');
  if (entries.isEmpty) {
    buffer.writeln('final List<ToolMod> kToolMods = <ToolMod>[];');
  } else {
    buffer.writeln('final List<ToolMod> kToolMods = <ToolMod>[');
    for (final entry in entries) {
      buffer.writeln(entry);
    }
    buffer.writeln('];');
  }
  buffer.writeln('// dart format on');
  return buffer.toString();
}

void _validateId(ModRegistration mod) {
  final id = mod.id;
  if (id.isEmpty || id.trim() != id || id.contains(RegExp(r'\s'))) {
    throw ModRegistryException('Mod id 不能为空、包含空白或首尾空格：${_quote(id)}');
  }
  if (id.contains('/') || id.contains('\\') || id.contains(':')) {
    throw ModRegistryException('Mod id 不能包含路径分隔符或冒号：$id');
  }
}

void _validateClassName(String id, String className) {
  if (!RegExp(r'^[A-Za-z_$][A-Za-z0-9_$]*$').hasMatch(className)) {
    throw ModRegistryException(
      'Mod $id 的注册类名不是合法的 Dart 标识符：${_quote(className)}',
    );
  }
}

void _validateImportSegments(String id, String path, String uri) {
  for (final segment in path.split('/')) {
    if (segment.isEmpty || segment == '.' || segment == '..') {
      throw ModRegistryException('Mod $id 的 import URI 不能包含空路径段、. 或 ..：$uri');
    }
    if (segment == '.git') {
      throw ModRegistryException('Mod $id 的 import URI 不能指向 .git：$uri');
    }
  }
}

String _resolveImportUri(String id, String uri) {
  if (uri.isEmpty || uri.trim() != uri || uri.contains(RegExp(r'\s'))) {
    throw ModRegistryException('Mod $id 的 import URI 不能为空或包含空白：${_quote(uri)}');
  }
  if (uri.contains('\\')) {
    throw ModRegistryException('Mod $id 的 import URI 必须使用 /：$uri');
  }
  if (uri.startsWith('package:')) {
    final rest = uri.substring('package:'.length);
    final slash = rest.indexOf('/');
    if (slash <= 0 || slash == rest.length - 1) {
      throw ModRegistryException('Mod $id 的 package import 必须包含包名和文件路径：$uri');
    }
    if (!uri.endsWith('.dart')) {
      throw ModRegistryException('Mod $id 的 import URI 必须指向 .dart 文件：$uri');
    }
    _validateImportSegments(id, rest.substring(slash + 1), uri);
    return uri;
  }
  if (uri.contains(':')) {
    throw ModRegistryException('Mod $id 的 import URI 只支持 package: 或相对路径：$uri');
  }
  if (uri.startsWith('/')) {
    throw ModRegistryException('Mod $id 的 import URI 不能是绝对路径：$uri');
  }
  if (!uri.endsWith('.dart')) {
    throw ModRegistryException('Mod $id 的 import URI 必须指向 .dart 文件：$uri');
  }

  _validateImportSegments(id, uri, uri);

  // 相对路径按 lib/ 解析；允许显式写 lib/ 前缀。
  final segments = uri.split('/');
  final target = <String>[
    'lib',
    if (segments.first == 'lib') ...segments.skip(1) else ...segments,
  ];
  if (target.length < 2) {
    throw ModRegistryException('Mod $id 的 import URI 缺少文件路径：$uri');
  }
  if (target.join('/') == modRegistryPath) {
    throw ModRegistryException('Mod $id 的 import URI 不能指向注册表自身：$uri');
  }

  var common = 0;
  while (common < _moddingDir.length &&
      common < target.length &&
      target[common] == _moddingDir[common]) {
    common++;
  }
  final relative = <String>[
    for (var i = common; i < _moddingDir.length; i++) '..',
    ...target.sublist(common),
  ];
  return relative.join('/');
}

const List<String> _moddingDir = <String>['lib', 'modding'];

String _importPrefix(String id, Set<String> used) {
  final buffer = StringBuffer();
  for (final rune in id.runes) {
    final char = String.fromCharCode(rune);
    buffer.write(RegExp(r'[A-Za-z0-9_]').hasMatch(char) ? char : '_');
  }
  final base = 'mod_${buffer.isEmpty ? 'unnamed' : buffer}';
  var candidate = base;
  var index = 2;
  while (!used.add(candidate)) {
    candidate = '${base}_$index';
    index++;
  }
  return candidate;
}

String _quote(String value) => "'$value'";
